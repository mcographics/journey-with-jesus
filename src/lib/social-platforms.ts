export type SocialPlatform = (typeof SOCIAL_PLATFORM_GROUPS)[number]["platforms"][number]["id"];
export const SOCIAL_PLATFORM_ITEMS = SOCIAL_PLATFORM_GROUPS.flatMap((group) => group.platforms);
export const SOCIAL_PLATFORM_LABELS = Object.fromEntries(
  SOCIAL_PLATFORM_ITEMS.map((platform) => [platform.id, platform.label]),
) as Record<SocialPlatform, string>;

export function socialPlatformUrlError(platform: SocialPlatform, url: string): string | null {
  let parsed: URL;
  try { parsed = new URL(url); } catch { return "Enter a valid HTTPS link."; }
  if (parsed.protocol !== "https:") return "Social links must use HTTPS.";
  const selected = SOCIAL_PLATFORM_ITEMS.find((item) => item.id === platform);
  if (!selected || selected.hosts.length === 0) return null;
  const hostname = parsed.hostname.toLowerCase();
  if (selected.hosts.some((host) => hostname === host || hostname.endsWith(`.${host}`))) return null;
  return `The ${selected.label} platform requires a link from ${selected.hosts.join(" or ")}. Choose the matching platform, or use Custom link.`;
}
